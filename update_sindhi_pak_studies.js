async function main() {
  const lines = rawSindhiText.trim().split('\n');
  const parsedSindhi = {};

  lines.forEach(line => {
    line = line.trim();
    if (!line || line.startsWith('#') || line.startsWith('باب') || line.startsWith('__')) return;
    const parts = line.split('\t').map(p => p.trim());
    if (parts.length >= 7) {
      const qNum = parseInt(parts[0], 10);
      if (!isNaN(qNum)) {
        parsedSindhi[qNum] = {
          t: parts[1],
          o: [parts[2], parts[3], parts[4], parts[5]],
          ansText: parts[6]
        };
      }
    }
  });

  console.log(`Parsed ${Object.keys(parsedSindhi).length} Sindhi questions.`);

  // Load existing seed_pak_studies.js
  let fileContent = fs.readFileSync('seed_pak_studies.js', 'utf8');

  // We will read pakStudiesQuestions from seed_pak_studies.js
  // and inject tSd (textSindhi) and oSd (optionsSindhi) into each object!
  const match = fileContent.match(/const pakStudiesQuestions = (\[[\s\S]*?\]);\s*async function/);
  if (!match) {
    console.error('Could not match pakStudiesQuestions in seed_pak_studies.js');
    return;
  }

  const pakStudiesQuestions = eval(match[1]);

  console.log(`Loaded ${pakStudiesQuestions.length} English questions from seed_pak_studies.js`);

  pakStudiesQuestions.forEach((q, idx) => {
    const qNum = idx + 1;
    const sd = parsedSindhi[qNum];
    if (sd) {
      q.tSd = sd.t;
      q.oSd = sd.o;
    }
  });

  // Re-serialize pakStudiesQuestions
  const newQuestionsCode = 'const pakStudiesQuestions = ' + JSON.stringify(pakStudiesQuestions, null, 2) + ';\n';

  // Replace pakStudiesQuestions in seed_pak_studies.js
  fileContent = fileContent.replace(/const pakStudiesQuestions = \[[\s\S]*?\];\s*async function/, newQuestionsCode + 'async function');

  // Make sure the insert query pushes textUr and optionsUr properly:
  // values.push(qId, q.t, q.tSd || q.t, q.o, q.oSd || q.o, q.c);
  fileContent = fileContent.replace(
    'values.push(qId, q.t, q.t, q.o, q.o, q.c);',
    'values.push(qId, q.t, q.tSd || q.t, q.o, q.oSd || q.o, q.c);'
  );

  fileContent = fileContent.replace(
    'ON CONFLICT (id) DO UPDATE SET "textEn"=EXCLUDED."textEn", "optionsEn"=EXCLUDED."optionsEn", "correctIndex"=EXCLUDED."correctIndex", subject=EXCLUDED.subject',
    'ON CONFLICT (id) DO UPDATE SET "textEn"=EXCLUDED."textEn", "textUr"=EXCLUDED."textUr", "optionsEn"=EXCLUDED."optionsEn", "optionsUr"=EXCLUDED."optionsUr", "correctIndex"=EXCLUDED."correctIndex", subject=EXCLUDED.subject'
  );

  fs.writeFileSync('seed_pak_studies.js', fileContent, 'utf8');
  console.log('✅ Updated seed_pak_studies.js with Sindhi translations!');

  // Now seed Neon DB directly!
  const client = new Client({ connectionString });
  await client.connect();
  console.log('✅ Connected to Neon DB...');
  await client.query('BEGIN');

  const BATCH_SIZE = 50;
  for (let i = 0; i < pakStudiesQuestions.length; i += BATCH_SIZE) {
    const chunk = pakStudiesQuestions.slice(i, i + BATCH_SIZE);
    const values = [];
    const valueStrings = [];

    chunk.forEach((q, idx) => {
      const qNum = i + idx + 1;
      const qId = `pak-std-q-${qNum}`;
      const offset = idx * 6;
      valueStrings.push(`($${offset + 1}, $${offset + 2}, $${offset + 3}, $${offset + 4}, $${offset + 5}, $${offset + 6}, 'Pakistan Studies', 'medium', NOW(), NOW())`);
      values.push(qId, q.t, q.tSd || q.t, q.o, q.oSd || q.o, q.c);
    });

    const sql = `
      INSERT INTO "Question" (id, "textEn", "textUr", "optionsEn", "optionsUr", "correctIndex", subject, difficulty, "createdAt", "updatedAt")
      VALUES ${valueStrings.join(', ')}
      ON CONFLICT (id) DO UPDATE SET "textEn"=EXCLUDED."textEn", "textUr"=EXCLUDED."textUr", "optionsEn"=EXCLUDED."optionsEn", "optionsUr"=EXCLUDED."optionsUr", "correctIndex"=EXCLUDED."correctIndex", subject=EXCLUDED.subject
    `;

    await client.query(sql, values);
    console.log(`  ✅ Seeded batch ${Math.floor(i / BATCH_SIZE) + 1}`);
  }

  await client.query('COMMIT');
  console.log('🎉 SUCCESS! All 364 Pakistan Studies MCQs updated with Sindhi translations in Neon DB!');
  await client.end();
}

main().catch(console.error);
